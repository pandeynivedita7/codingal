a = 5      # 0101 in binary
b = 3      # 0011 in binary

print(a & b)    # 1  -> 0001 and
print(a | b)    # 7  -> 0111 or  
print(a ^ b)    # 6  -> 0110 bitwise or
print(~a)       # -6 -> (2's complement of 5) 1's complement
print(a << 1)   # 10 -> 1010 right shift
print(a >> 1)   # 2  -> 0010 left shift
print( a * b )     # exclusive or

