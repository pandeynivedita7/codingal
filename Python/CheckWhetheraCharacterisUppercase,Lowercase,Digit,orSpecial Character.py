ch = input("Enter a character: ")

if ch.isalpha():
    if ch.isupper():
        print("It is an Uppercase Letter.")
    else:
        print("It is a Lowercase Letter.")
elif ch.isdigit():
    print("It is a Digit.")
else:
    print("It is a Special Character.")


