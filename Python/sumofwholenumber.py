# Input an integer value
n = int(input("Enter the number whose sum you want to find: "))#10

# Initialize sum
sum = 0# storing result

# Iterate from 1 to n (inclusive)
for i in range(1, n+1):# start 1 end till 10
    sum += i #sum =sum+i     a+=1 a=a+1
#sum-=i sum=sum-i
# Print the result
print("\nSum =", sum)
