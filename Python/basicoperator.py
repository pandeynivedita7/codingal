# Basic Operator Examples in Python

# 1. Arithmetic Operators
a = 10
b = 3
print("Arithmetic Operators:")
print("Addition:", a + b)
print("Subtraction:", a - b)
print("Multiplication:", a * b)
print("Division:", a / b)
print("Modulus:", a % b)
print("Exponent:", a ** b)
print("Floor Division:", a // b)

# 2. Comparison Operators
print("\nComparison Operators:")
print("a > b:", a > b)
print("a < b:", a < b)
print("a == b:", a == b)
print("a != b:", a != b)

# 3. Logical Operators
x = True
y = False
print("\nLogical Operators:")
print("x and y:", x and y)
print("x or y:", x or y)
print("not x:", not x)

# 4. Assignment Operators
print("\nAssignment Operators:")
c = 5
print("Initial c:", c)
c += 2
print("c += 2:", c)
c *= 3
print("c *= 3:", c)

# 5. Bitwise Operators 0 and 1 10 11 100 binary number
print("\nBitwise Operators:")
print("a & b:", a & b)# and
print("a | b:", a | b)#or
print("a ^ b:", a ^ b)# not
print("~a:", ~a)# negation
print("a << 1:", a << 1)
print("a >> 1:", a >> 1)
