# Summertime Checker Program

# Take input from user
month = int(input("Enter month number (1-12): "))

# Check using if-else
if (month >= 4 and month <= 6):#and is an operator that gives value true if both condition is true logic operator and or not
    print("It's Summer Time!")# and means all true o/p true
else:# or true is anycondition true not opp true and false
    print("It's not Summer Time.")
