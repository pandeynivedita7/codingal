public class DataTypesExample {// student informatiom
    public static void main(String[] args) {

        // Primitive data types
        byte age = 25; //age int
        short year = 2025;// double weight
        int population = 1400000000; // char grade 
        long distance = 9876543210L;// boolean is_student

        float height = 5.6f;
        double weight = 58.75;

        char grade = 'A';
        boolean isStudent = true;

        // Display values
        System.out.println("Age (byte): " + age);
        System.out.println("Year (short): " + year);
        System.out.println("Population (int): " + population);
        System.out.println("Distance (long): " + distance);
        System.out.println("Height (float): " + height);
        System.out.println("Weight (double): " + weight);
        System.out.println("Grade (char): " + grade);
        System.out.println("Is Student (boolean): " + isStudent);
    }
}
