public class EscapeSequencesDemo {
    public static void main(String[] args) {

        // Demonstrating quotation marks
        System.out.println("This allows for quotations: \"Hello World\"");
        System.out.println("'hello maam'");

        // Demonstrating backslash
        System.out.println("This includes a backslash: \\");

        // Demonstrating new line
        System.out.println("This creates \na line break");

        // Demonstrating tab space
        System.out.println("This adds a \ttab space");

        // Combined example
        System.out.println("Line1\tTabbed\nLine2 with \"quotes\" and a backslash \\");
    }
}
