class ModulusExamples {
    public static void main(String[] args) {

        // Example 1: Check if a number is even or odd
        int number = 15;
        if (number % 2 == 0) {
            System.out.println(number + " is Even");
        } else {
            System.out.println(number + " is Odd");
        }
    }
}